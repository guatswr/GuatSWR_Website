import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createRouteProgress, createRouteProgressState } from '../app/utils/route-progress'

describe('navigation progress ownership', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())
  const setup = (reduced = false) => {
    const state = createRouteProgressState()
    return { state, controller: createRouteProgress(state, () => reduced) }
  }
  it('never reports completion just because a request is slow', () => {
    const { state, controller } = setup()
    controller.start('/members')
    vi.advanceTimersByTime(60_000)
    expect(state.phase).toBe('loading')
    expect(state.progress).toBeGreaterThan(0.8)
    expect(state.progress).toBeLessThan(1)
    controller.dispose()
    expect(vi.getTimerCount()).toBe(0)
  })
  it('ignores late completion and cancellation of an earlier navigation', () => {
    const { state, controller } = setup()
    const old = controller.start('/members')
    const latest = controller.start('/history')
    controller.complete(old)
    controller.cancel(old)
    expect(state.phase).toBe('loading')
    expect(state.path).toBe('/history')
    controller.complete(latest)
    expect(state.progress).toBe(1)
    expect(state.phase).toBe('complete')
    controller.dispose()
  })
  it('distinguishes two visits to the same path', () => {
    const { state, controller } = setup()
    const old = controller.start('/members')
    controller.start('/members')
    controller.complete(old)
    expect(state.phase).toBe('loading')
    controller.dispose()
  })
  it('cancels old hide/reset timers when a new navigation starts', () => {
    const { state, controller } = setup()
    controller.complete(controller.start('/members'))
    vi.advanceTimersByTime(180)
    expect(state.phase).toBe('hiding')
    controller.start('/history')
    vi.advanceTimersByTime(1000)
    expect(state.phase).toBe('loading')
    expect(state.progress).toBeGreaterThan(0)
    controller.dispose()
  })
  it('holds the full bar before fading and resetting invisibly', () => {
    const { state, controller } = setup()
    controller.complete(controller.start('/members'), true)
    expect(state.error).toBe(true)
    vi.advanceTimersByTime(180)
    expect(state.phase).toBe('hiding')
    expect(state.progress).toBe(1)
    vi.advanceTimersByTime(250)
    expect(state.phase).toBe('idle')
    expect(state.progress).toBe(0)
    expect(vi.getTimerCount()).toBe(0)
  })
  it('keeps reduced-motion progress static until the page is ready', () => {
    const { state, controller } = setup(true)
    const token = controller.start('/members')
    vi.advanceTimersByTime(5000)
    expect(state.progress).toBe(0.12)
    controller.complete(token)
    expect(state.progress).toBe(1)
    controller.dispose()
  })
})
