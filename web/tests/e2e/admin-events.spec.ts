const base = Number(process.env.E2E_PORT_BASE ?? 3100), fixture = `http://127.0.0.1:${base + 82}`
const png = { name: 'avatar.png', mimeType: 'image/png', buffer: publicImageFixtures['.png'].body() }
async function login(page: Page, ordinary = false) {
  await page.goto('/login?redirect=%2Fadmin%2Fevents')
  await page.getByLabel('Username').fill(ordinary ? 'second' : 'admin')
  await page.getByLabel('Password', { exact: true }).fill(ordinary ? 'secondpass' : 'adminpass')
  if (ordinary) await page.getByLabel('二步密码 (可选)').fill('123456')
  await page.getByRole('button', { name: '登录系统', exact: true }).click()
  await page.getByRole('button', { name: '进入管理端', exact: true }).click()
  await expect(page.locator('.admin-panel-heading h2')).toHaveText('活动管理')
}
async function confirm(page: Page) {
  const button = page.getByRole('button', { name: '确认执行', exact: true })
  await button.click()
  await expect(button).toHaveCount(0)
}
const card = (page: Page, title: string) => page.getByTestId('admin-event-card').filter({ has: page.locator('h3', { hasText: title }) })
async function screen(page: Page, info: TestInfo, name: string) {
  await expect(page.locator('.el-message')).toHaveCount(0)
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => window.scrollTo(0, 0))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await info.attach(name, { body: await page.screenshot({ fullPage: true, animations: 'disabled' }), contentType: 'image/png' })
}

