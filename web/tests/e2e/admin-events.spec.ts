test('pending review, protected detail, status changes, deletion and restoration invalidate warmed public reads', async ({ page, request }, info) => {
  test.setTimeout(60_000)
  expect((await request.get('/api/event/2001')).status()).toBe(404)
  await request.get('/api/event')
  await login(page)
  const pending = card(page, '等待审核的赛事')
  await pending.getByRole('button', { name: '查看详情', exact: true }).click()
  await expect(page.getByText('秋季 STG 大会，欢迎新老群友参加。', { exact: true })).toBeVisible()
  const detail = await page.request.get('/api/bff/admin/events/2001')
  expect(detail.status()).toBe(200)
  expect(await detail.text()).not.toContain('visitor_ip')
  await page.getByRole('button', { name: '返回活动列表', exact: true }).click()
  await pending.getByRole('button', { name: '审核通过', exact: true }).click(); await confirm(page)
  await expect(pending).toHaveCount(0)
  expect((await request.get('/api/event/2001')).status()).toBe(200)
  expect((await (await request.get('/api/event')).json()).items.some((row: { id: number }) => row.id === 2001)).toBe(true)
  await page.getByLabel('筛选状态', { exact: true }).selectOption('published')
  await expect(pending).toBeVisible()
  await pending.getByLabel('调整状态', { exact: true }).selectOption('ongoing'); await confirm(page)
  await expect(pending).toHaveCount(0)
  expect((await (await request.get('/api/event/2001')).json()).status).toBe('ongoing')
  await page.getByLabel('筛选状态', { exact: true }).selectOption('ongoing')
  await pending.getByRole('button', { name: '删除活动', exact: true }).click(); await confirm(page)
  await expect(pending).toHaveCount(0)
  expect((await request.get('/api/event/2001')).status()).toBe(404)
  await page.getByLabel('筛选状态', { exact: true }).selectOption('deleted')
  await pending.getByLabel('调整状态', { exact: true }).selectOption('published'); await confirm(page)
  await expect(pending).toHaveCount(0)
  expect((await request.get('/api/event/2001')).status()).toBe(200)
  await page.getByLabel('筛选状态', { exact: true }).selectOption('')
  for (const theme of ['light', 'dark']) {
    if (theme === 'dark') await page.getByRole('button', { name: '切换为夜间模式' }).click()
    await expect(pending).toBeVisible()
    await screen(page, info, `event-management-${theme}`)
  }
})

