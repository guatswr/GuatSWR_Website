test('event avatar BFF enforces session, Origin, CSRF, public status and server-bound event storage', async ({ page, request }) => {
  const endpoint = '/api/bff/admin/events/101/avatar'
  expect((await request.post(endpoint, { multipart: { file: png } })).status()).toBe(401)
  await login(page)
  const csrf = (await (await page.request.get('/api/bff/auth/csrf')).json()).csrfToken as string
  const initial = await (await request.get(`${fixture}/__fixture/events`)).json()
  const blocked = await page.request.post(endpoint, { headers: { origin: `http://127.0.0.1:${base}` }, multipart: { file: png } })
  expect(blocked.status()).toBe(403)
  expect((await page.request.post(endpoint, { headers: { origin: 'https://invalid.example', 'x-csrf-token': csrf }, multipart: { file: png } })).status()).toBe(403)
  const denied = await (await request.get(`${fixture}/__fixture/events`)).json()
  expect(denied.requests).toHaveLength(initial.requests.length)
  const headers = { origin: `http://127.0.0.1:${base}`, 'x-csrf-token': csrf }
  expect((await page.request.post('/api/bff/admin/events/2001/avatar', { headers, multipart: { file: png } })).status()).toBe(403)
  const large = { ...png, buffer: Buffer.concat([png.buffer, Buffer.alloc(9 * 1024 * 1024 - png.buffer.length)]) }
  const allowed = await page.request.post(endpoint, { headers, multipart: { file: large, eid: '2001' } })
  expect(allowed.status()).toBe(200)
  expect((await allowed.json()).url).toMatch(/^\/uploads\/img\/events\/101\/avatars\//)
  const after = await (await request.get(`${fixture}/__fixture/events`)).json()
  const uploads = after.requests.slice(initial.requests.length).filter((call: { path: string }) => call.path === '/api/upload/visitor/avatar')
  expect(uploads).toHaveLength(1)
  expect(uploads[0].upload).toMatchObject({ eid: 101, name: 'upload.png', type: 'image/png', size: 9 * 1024 * 1024, fields: ['file', 'eid'] })
  expect(uploads[0].headers.authorization).toMatch(/^Bearer /)
  expect(uploads[0].headers.cookie).toBeUndefined()
  expect(uploads[0].headers.origin).toBeUndefined()
})
