import { spawn, execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { randomBytes } from 'node:crypto'
import { createServer } from 'node:net'

const exec = promisify(execFile)
const root = fileURLToPath(new URL('../../', import.meta.url))
const require = createRequire(new URL('../../backend/package.json', import.meta.url))
const { Pool } = require('pg')
const business = process.argv.includes('--business')
export const POSTGRES_TEST_IMAGE = 'postgres:18.6-bookworm@sha256:f1ea2a1a4fb7b68d4836be1fdcb8a6466a89b072158bf9d97663600538c294c5'
let container
let admin
try {
  if (Number(process.versions.node.split('.')[0]) !== 24) throw Error('Node 24 required')
  const name = `guatswr-pg-contract-${randomBytes(8).toString('hex')}`
  const reservation = createServer()
  await new Promise((resolve, reject) => { reservation.once('error', reject); reservation.listen(0, '127.0.0.1', resolve) })
  const port = reservation.address().port
  await new Promise((resolve, reject) => reservation.close(error => error ? reject(error) : resolve()))
  container = (await exec('docker', ['run', '--detach', '--name', name, '--label', 'io.guatswr.test=postgres-adapters',
    '--memory=256m', '--pids-limit=128', '--cpus=1', '--volume', '/var/lib/postgresql',
    '--publish', `127.0.0.1:${port}:5432`, '-e', 'POSTGRES_USER=guatswr_migrator', '-e', 'POSTGRES_DB=guatswr_pg_contract_test',
    '-e', 'POSTGRES_PASSWORD=isolated-test-only', POSTGRES_TEST_IMAGE], { timeout: 120000 })).stdout.trim()
  const binding = (await exec('docker', ['port', container, '5432/tcp'])).stdout.trim()
  if (binding !== `127.0.0.1:${port}`) throw Error('Loopback-only PostgreSQL binding required')
  let ready = false
  for (let attempt = 0; attempt < 60; attempt++) {
    try { await exec('docker', ['exec', container, 'pg_isready', '-h', '127.0.0.1', '-U', 'guatswr_migrator']); ready = true; break }
    catch { await new Promise(resolve => setTimeout(resolve, 500)) }
  }
  if (!ready) throw Error('Isolated PostgreSQL did not become ready')
  const base = `127.0.0.1:${port}/guatswr_pg_contract_test`
  admin = new Pool({ connectionString: `postgres://guatswr_migrator:isolated-test-only@${base}`, max: 1 })
  await admin.query(`
    CREATE ROLE guatswr_app LOGIN PASSWORD 'isolated-test-only';
    REVOKE CREATE ON SCHEMA public FROM PUBLIC;
    CREATE SCHEMA main; CREATE SCHEMA audit; CREATE SCHEMA bff;
    CREATE TABLE main.items(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label TEXT UNIQUE, parent_id BIGINT REFERENCES main.items(id), value BYTEA);
    CREATE TABLE main.site_config(key TEXT PRIMARY KEY, value TEXT);
    CREATE TABLE audit.audit_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, details TEXT);
    CREATE TABLE bff.records(key TEXT PRIMARY KEY, value BYTEA);
    GRANT CONNECT ON DATABASE guatswr_pg_contract_test TO guatswr_app;
    GRANT USAGE ON SCHEMA main,audit,bff TO guatswr_app;
    GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA main,audit,bff TO guatswr_app;
    GRANT USAGE ON ALL SEQUENCES IN SCHEMA main,audit,bff TO guatswr_app;
  `)
  console.log(JSON.stringify({ image: POSTGRES_TEST_IMAGE, server: (await admin.query('SHOW server_version')).rows[0].server_version,
    isolated: true, productionConnections: false }))
  if (business) {
    await admin.query('CREATE DATABASE guatswr_pg_business_template')
    const { initializePostgres } = require(join(root, 'backend/dist/src/migrations/postgres/engine.js'))
    await initializePostgres(`postgres://guatswr_migrator:isolated-test-only@127.0.0.1:${port}/guatswr_pg_business_template`, 'guatswr_pg_business_template', 'guatswr_app')
  }
  await admin.end(); admin = undefined
  const entry = join(dirname(require.resolve('vitest/package.json')), 'vitest.mjs')
  const selected = process.argv.slice(2).filter(value => /^tests\/[a-zA-Z0-9_./-]+\.test\.mjs$/.test(value))
  const child = spawn(process.execPath, [entry, 'run', '--configLoader', 'native', '--config', business ? 'vitest.postgres.config.mjs' : 'vitest.database.config.mjs', ...selected], {
    cwd: join(root, 'backend'), stdio: 'inherit', env: { ...process.env,
      PG_ADAPTER_TEST_URL: `postgres://guatswr_app:isolated-test-only@${base}`,
      PG_ADAPTER_ADMIN_URL: `postgres://guatswr_migrator:isolated-test-only@${base}`,
      PG_ADAPTER_CONTAINER: container,
      ...(business ? { PG_BUSINESS_ADMIN_URL: `postgres://guatswr_migrator:isolated-test-only@${base}` } : {}),
    },
  })
  process.exitCode = await new Promise((resolve, reject) => { child.once('error', reject); child.once('exit', code => resolve(code ?? 1)) })
} catch (error) {
  console.error('PostgreSQL adapter test failed:', error?.code || 'TEST_SETUP_FAILED',
    String(error?.message || '').replace(/postgres(?:ql)?:\/\/\S+/g, '<redacted>').slice(0, 180))
  process.exitCode = 1
} finally {
  await admin?.end()
  if (container && /^[a-f0-9]{64}$/.test(container)) {
    const label = (await exec('docker', ['inspect', '--format', '{{index .Config.Labels "io.guatswr.test"}}', container])).stdout.trim()
    if (label !== 'postgres-adapters') throw Error('Refusing to remove an unrelated container')
    await exec('docker', ['rm', '--force', '--volumes', container])
  }
}
