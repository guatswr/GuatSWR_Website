const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { start } = require('../server');
(async () => {
  const fs = require('node:fs/promises');
  const os = require('node:os');
  const path = require('node:path');
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'guatswr-runtime-'));
  process.env.DATA_DIR = path.join(root, 'data');
  process.env.PUBLIC_DIR = path.join(root, 'public');
  process.env.BACKUP_ROOT = path.join(root, 'backups');
  process.env.TRUST_PROXY_CIDRS = '127.0.0.1/32';
  process.env.GUEST_DRAFT_PROOF_MODE = 'required';
  await require('./initialize-databases.cjs').initializeDatabases({}, { data: process.env.DATA_DIR });
  const bootstrapArgs = [path.resolve('dist/src/admin/bootstrap-cli.js'), '--main-db', path.join(process.env.DATA_DIR, 'guatswr_web_main.db')];
  const bootstrapEnv = { ...process.env, SUPER_ADMIN_USERNAME: 'synthetic-initial-admin', SUPER_ADMIN_PASSWORD: 'synthetic-bootstrap-password' };
  assert.deepEqual(JSON.parse(execFileSync(process.execPath, bootstrapArgs, { env: bootstrapEnv, encoding: 'utf8' })), { bootstrap: 'created' });
  assert.deepEqual(JSON.parse(execFileSync(process.execPath, bootstrapArgs, { env: bootstrapEnv, encoding: 'utf8' })), { bootstrap: 'unchanged' });
  const instance = await start();
  try {
    const version = await new Promise((resolve, reject) => instance.context.db.get('SELECT sqlite_version() AS version', (err, row) => err ? reject(err) : resolve(row.version)));
    const response = await fetch(`http://127.0.0.1:${instance.app.get('port') || process.env.PORT}/api/version`);
    assert.equal(response.status, 200);
    assert.equal((await response.json()).status, 'online');
    const main = await instance.context.sql.main.transaction(tx => tx.get('SELECT count(*) AS count FROM users'));
    const audit = await instance.context.sql.audit.get('SELECT count(*) AS count FROM audit_logs');
    assert.ok(Number.isInteger(main.count) && Number.isInteger(audit.count));
    const user = await instance.context.sql.main.run('INSERT INTO users(username,password,role) VALUES (?,?,?)',
      ['synthetic-smoke', require('bcryptjs').hashSync('synthetic-password', 4), 'admin']);
    const token = require('jsonwebtoken').sign({ id: user.lastID, token_version: 0 }, process.env.JWT_SECRET);
    const origin = `http://127.0.0.1:${instance.app.get('port') || process.env.PORT}`;
    const saved = await fetch(`${origin}/api/config`, { method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ key: 'banner_text', value: 'synthetic-config-smoke' }) });
    assert.equal(saved.status, 200);
    assert.deepEqual(await saved.json(), { message: '已保存' });
    const config = await fetch(`${origin}/api/config`);
    assert.equal(config.status, 200);
    assert.equal((await config.json()).banner_text, 'synthetic-config-smoke');
    const publicLogs = await fetch(`${origin}/api/logs`);
    assert.equal(publicLogs.status, 200);
    const projectedLogs = await publicLogs.json();
    assert.ok(Array.isArray(projectedLogs.logs));
    assert.ok(projectedLogs.logs.every(row => !Object.hasOwn(row, 'user_id')));
    assert.equal((await fetch(`${origin}/api/logs/stats`)).status, 200);
    assert.equal((await fetch(`${origin}/api/logs/umami`)).status, 503);
    const history = await fetch(`${origin}/api/history`, { method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ date: '2026-10-23', title: 'synthetic-history-smoke' }) });
    assert.equal(history.status, 200);
    const created = await history.json();
    assert.ok(Number.isSafeInteger(created.id) && created.id > 0);
    const listed = await fetch(`${origin}/api/history`);
    assert.equal(listed.status, 200);
    assert.ok((await listed.json()).some(entry => entry.id === created.id && entry.title === 'synthetic-history-smoke'));
    const member = await fetch(`${origin}/api/members`, { method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ name: 'synthetic-member-smoke', role: 'member', tags: ['tag', 'tag'] }) });
    assert.equal(member.status, 200);
    const memberCreated = await member.json();
    assert.ok(Number.isSafeInteger(memberCreated.id) && memberCreated.id > 0);
    const members = await fetch(`${origin}/api/members`);
    assert.equal(members.status, 200);
    const projected = (await members.json()).find(entry => entry.id === memberCreated.id);
    assert.deepEqual(projected.tags, ['tag']);
    assert.equal(projected.avatar_original, null);
    const cleanupUrl = '/uploads/img/runtime-cleanup.png';
    await fs.writeFile(path.join(process.env.PUBLIC_DIR, 'img', 'runtime-cleanup.png'), 'synthetic-cleanup-bytes');
    await instance.context.sql.main.run('UPDATE members SET avatar=?,deleted_at=CURRENT_TIMESTAMP WHERE id=?', [cleanupUrl, memberCreated.id]);
    const owner = await instance.context.sql.main.get("SELECT id FROM users WHERE username='synthetic-initial-admin'");
    const ownerToken = require('jsonwebtoken').sign({ id: owner.id, token_version: 0 }, process.env.JWT_SECRET);
    const purge = await fetch(`${origin}/api/admin/recycle-bin/purge`, { method: 'POST', headers: { authorization: `Bearer ${ownerToken}` } });
    assert.equal(purge.status, 200);
    const cleanupJob = await instance.context.sql.main.get('SELECT id,state FROM asset_cleanup_jobs WHERE url=?', [cleanupUrl]);
    assert.equal(cleanupJob.state, 'quarantined');
    assert.equal(await fs.readFile(path.join(process.env.DATA_DIR, 'asset-quarantine', cleanupJob.id), 'utf8'), 'synthetic-cleanup-bytes');
    const activity = await fetch(`${origin}/api/activities`, { method: 'POST', headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: JSON.stringify({ title: 'synthetic-activity-smoke', tag: 'STG', date: '2026-10-23' }) });
    assert.equal(activity.status, 200);
    const activityCreated = await activity.json();
    assert.ok(Number.isSafeInteger(activityCreated.id) && activityCreated.id > 0);
    const sitemap = await fetch(`${origin}/sitemap.xml`);
    assert.equal(sitemap.status, 200);
    assert.match(sitemap.headers.get('content-type'), /application\/xml/);
    assert.ok((await sitemap.text()).includes(`/activity/${activityCreated.id}</loc>`));
    const activities = await fetch(`${origin}/api/activities`);
    assert.equal(activities.status, 200);
    const activityRow = (await activities.json()).items.find(entry => entry.id === activityCreated.id);
    assert.equal(activityRow.created_by, user.lastID);
    const detail = await fetch(`${origin}/api/activities/${activityCreated.id}`);
    assert.equal(detail.status, 200);
    assert.equal((await detail.json()).created_by, 'synthetic-smoke');
    const signupEvent = await instance.context.sql.main.run("INSERT INTO events(type,title,status,content) VALUES ('STG','synthetic-signup','published','{}')");
    const signupHeaders = { authorization: `Bearer ${token}`, 'content-type': 'application/json' };
    const signupUrl = `${origin}/api/event/${signupEvent.lastID}/signup`;
    const signup = await fetch(signupUrl, { method: 'POST', headers: signupHeaders, body: JSON.stringify({ common_id: 'synthetic-participant', qq: '12345', avatar: '/uploads/avatar.png' }) });
    assert.equal(signup.status, 200);
    const signupRead = await fetch(signupUrl, { headers: signupHeaders });
    const signupRow = (await signupRead.json()).data;
    assert.equal(signupRow.common_id, 'synthetic-participant');
    assert.equal(signupRow.visitor_ip, undefined);
    assert.equal((await fetch(signupUrl, { method: 'DELETE', headers: signupHeaders })).status, 200);
    assert.equal((await instance.context.sql.main.get('SELECT count(*) AS n FROM event_participants WHERE event_id=?', [signupEvent.lastID])).n, 0);
    const eventUrl = `${origin}/api/event/${signupEvent.lastID}`;
    assert.equal((await fetch(`${eventUrl}/set_result`, { method: 'POST', headers: signupHeaders, body: JSON.stringify({ results: [{ rank: 1 }] }) })).status, 200);
    assert.equal((await fetch(`${eventUrl}/settle`, { method: 'POST', headers: signupHeaders, body: JSON.stringify({ payload: { completion: true } }) })).status, 200);
    const settledEvent = await instance.context.sql.main.get('SELECT status,content FROM events WHERE id=?', [signupEvent.lastID]);
    assert.equal(settledEvent.status, 'settled');
    assert.deepEqual(JSON.parse(settledEvent.content).results, [{ rank: 1 }]);
    assert.equal(JSON.parse(settledEvent.content).completion, true);
    assert.equal((await fetch(`${origin}/api/admin/events/${signupEvent.lastID}/review`, { method: 'POST', headers: signupHeaders, body: JSON.stringify({ action: 'approve' }) })).status, 200);
    const bridge = { 'x-bff-bridge': process.env.BFF_BRIDGE_SECRET, 'x-forwarded-for': '127.0.0.1', 'content-type': 'application/json' };
    const proof = (scope, eid) => {
      const expires = Math.floor(Date.now() / 1000) + 30;
      const message = require('@guatswr/shared').guestDraftProofMessage({ scope, eid, expires, ip: '127.0.0.1' });
      return `v1.${eid}.${scope}.${expires}.${require('node:crypto').createHmac('sha256', process.env.BFF_BRIDGE_SECRET).update(message).digest('base64url')}`;
    };
    assert.equal((await fetch(`${origin}/api/event/draft`, { method: 'POST', headers: bridge, body: '{}' })).status, 403);
    const guest = await fetch(`${origin}/api/event/draft`, { method: 'POST', headers: { ...bridge, 'x-bff-draft-proof': proof('draft', 0) }, body: '{}' });
    assert.equal(guest.status, 200);
    const guestId = (await guest.json()).id;
    const saveHeaders = { ...bridge, 'x-bff-draft-proof': proof('save', guestId) };
    assert.equal((await fetch(`${origin}/api/event/${guestId + 1}`, { method: 'PUT', headers: saveHeaders, body: JSON.stringify({ title: 'cross-draft rejected' }) })).status, 403);
    assert.equal((await fetch(`${origin}/api/event/${guestId}`, { method: 'PUT', headers: saveHeaders, body: JSON.stringify({ content: { results: [{ rank: 1 }] } }) })).status, 400);
    assert.equal((await fetch(`${origin}/api/event/${guestId}`, { method: 'PUT', headers: saveHeaders, body: JSON.stringify({ title: 'synthetic-proof-smoke', content: { initiator: { id: 'synthetic-person-id' } } }) })).status, 200);
    console.log(JSON.stringify({ node: process.version, platform: process.platform, sqlite: version, sqliteCli: execFileSync('sqlite3',['--version'],{encoding:'utf8'}).trim(), sharp: require('sharp').versions.sharp, scopedSql: true, typedConfig: true, typedHistory: true, typedMembers: true, typedActivities: true, requiredDraftProof: true, guestContentPolicy: true }));
  } finally {
    await instance.close();
    if (path.dirname(root) !== path.resolve(os.tmpdir()) || !path.basename(root).startsWith('guatswr-runtime-')) throw new Error('Unsafe smoke cleanup');
    await fs.rm(root, { recursive: true, force: true });
  }
})().catch((error) => { console.error(error); process.exitCode=1; });
