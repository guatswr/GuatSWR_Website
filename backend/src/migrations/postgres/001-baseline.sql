CREATE FUNCTION main.is_calendar_date(value text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE STRICT SET search_path=pg_catalog AS $$
BEGIN
  IF value !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' OR left(value,4)='0000' THEN RETURN false; END IF;
  RETURN to_char(value::date,'YYYY-MM-DD')=value;
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN RETURN false;
END $$;
